/**
 * Retrieve the Bangla step translation for a specific item and step index.
 */
export function getStepTranslation(
  itemId: string,
  stepIdx: number,
  instructionEn: string,
  titleEn?: string
): StepTranslation {
  const itemSteps = STEP_TRANSLATIONS[itemId];
  if (itemSteps && itemSteps[stepIdx]) {
    return itemSteps[stepIdx];
  }

  // If item or step was not directly indexed, provide a clean contextual translation
  return {
    titleBn: titleEn,
    instructionBn: instructionEn,
  };
}
